//! Generates the TypeScript IPC types into `apps/desktop/src/ipc/generated`.
//!
//! `cargo test -p whimbrel bindings` fails when the committed files are stale;
//! `WHIMBREL_UPDATE_BINDINGS=1 cargo test -p whimbrel bindings` rewrites them.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};

use crate::error::AppError;
use crate::ipc::{RequestCancelArgs, RequestSendArgs};

const HEADER: &str = "// Generated by src-tauri/src/bindings.rs. Do not edit.\n";

fn generated_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/ipc/generated")
}

/// Exports every root type and its dependencies into `dir`.
fn export_all(dir: &Path) {
    // serde_json writes 64-bit integers as JSON numbers, so `number` is what JavaScript receives.
    let config = Config::new().with_large_int("number").with_out_dir(dir);
    AppError::export_all(&config).unwrap();
    RequestSendArgs::export_all(&config).unwrap();
    RequestCancelArgs::export_all(&config).unwrap();
    wbl_http::Response::export_all(&config).unwrap();
    wbl_http::HttpErrorCode::export_all(&config).unwrap();
    write_index(dir);
}

fn write_index(dir: &Path) {
    let mut names: Vec<String> = fs::read_dir(dir)
        .unwrap()
        .map(|entry| entry.unwrap().file_name().to_string_lossy().into_owned())
        .filter_map(|name| name.strip_suffix(".ts").map(str::to_owned))
        .filter(|name| name != "index")
        .collect();
    names.sort();
    let exports: String = names
        .iter()
        .map(|name| format!("export type * from \"./{name}\";\n"))
        .collect();
    fs::write(dir.join("index.ts"), format!("{HEADER}{exports}")).unwrap();
}

fn read_dir_contents(dir: &Path) -> BTreeMap<String, String> {
    let Ok(entries) = fs::read_dir(dir) else {
        return BTreeMap::new();
    };
    entries
        .map(|entry| {
            let path = entry.unwrap().path();
            let name = path.file_name().unwrap().to_string_lossy().into_owned();
            (name, fs::read_to_string(&path).unwrap())
        })
        .collect()
}

#[test]
fn bindings_are_up_to_date() {
    let fresh = tempfile::tempdir().unwrap();
    export_all(fresh.path());
    let expected = read_dir_contents(fresh.path());
    let target = generated_dir();

    if std::env::var_os("WHIMBREL_UPDATE_BINDINGS").is_some() {
        if target.exists() {
            fs::remove_dir_all(&target).unwrap();
        }
        fs::create_dir_all(&target).unwrap();
        for (name, contents) in &expected {
            fs::write(target.join(name), contents).unwrap();
        }
    }

    let actual = read_dir_contents(&target);
    assert!(
        actual == expected,
        "TypeScript bindings are stale; run `WHIMBREL_UPDATE_BINDINGS=1 cargo test -p whimbrel bindings`"
    );
}
